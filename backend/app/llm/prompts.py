def build_user_prompt(query: str, chunks: List[RAGChunk]) -> str:
    """Builds a formatted prompt incorporating verified knowledge context chunks."""
    if not chunks:
        context_str = "No relevant verified policy documents were found in the knowledge base."
    else:
        formatted_chunks = []
        for i, chunk in enumerate(chunks, 1):
            formatted_chunks.append(
                f"--- CONTEXT DOCUMENT {i}: {chunk.document} (Relevance: {int(chunk.score * 100)}%) ---\n"
                f"{chunk.content}"
            )
        context_str = "\n\n".join(formatted_chunks)

    return f"""VERIFIED INSTITUTIONAL CONTEXT:
{context_str}

USER QUERY:
{query}

Please provide an accurate, grounded answer based strictly on the verified context above."""


